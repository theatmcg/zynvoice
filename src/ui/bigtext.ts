/** 5-pixel-tall bitmap font rendered into 3 terminal rows with half blocks. */
const GLYPHS: Record<string, string[]> = {
  "0": ["111", "101", "101", "101", "111"],
  "1": ["010", "110", "010", "010", "111"],
  "2": ["111", "001", "111", "100", "111"],
  "3": ["111", "001", "111", "001", "111"],
  "4": ["101", "101", "111", "001", "001"],
  "5": ["111", "100", "111", "001", "111"],
  "6": ["111", "100", "111", "101", "111"],
  "7": ["111", "001", "001", "001", "001"],
  "8": ["111", "101", "111", "101", "111"],
  "9": ["111", "101", "111", "001", "111"],
  $: ["011", "110", "010", "011", "110"],
  ",": ["0", "0", "0", "1", "1"],
  ".": ["0", "0", "0", "0", "1"],
  h: ["100", "100", "111", "101", "101"],
  " ": ["0", "0", "0", "0", "0"],
};

const HALF: Record<string, string> = { "11": "█", "10": "▀", "01": "▄", "00": " " };

export function bigText(text: string): string[] {
  const rows = ["", "", ""];
  [...text].forEach((ch, i) => {
    const g = GLYPHS[ch] ?? GLYPHS[" "];
    const px = [...g, "0".repeat(g[0].length)];
    for (let r = 0; r < 3; r++) {
      let line = "";
      for (let x = 0; x < g[0].length; x++) line += HALF[px[r * 2][x] + px[r * 2 + 1][x]];
      rows[r] += (i ? " " : "") + line;
    }
  });
  return rows;
}
